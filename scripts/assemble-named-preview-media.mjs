// Run after both named-preview capture scripts finish successfully.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {VIDEO_CATALOG} from '../shared/video-catalog.mjs';
import {flagshipTemplates} from '../shared/flagship-templates.mjs';
import {cinorevTemplates} from '../shared/cinorev-templates.mjs';
import {theeramTemplate} from '../shared/theeram-template.mjs';
import {thiruvarulTemplate} from '../shared/thiruvarul-template.mjs';
import {payanamTemplate} from '../shared/kalyana-payanam-template.mjs';

const read=async path=>JSON.parse(await fs.readFile(path,'utf8'));
const websites=await read('work/preview-names/website-media.json');
const videos=await read('work/preview-names/video-media.json');
const websiteIds=[...flagshipTemplates,...cinorevTemplates.map(t=>t.template),theeramTemplate,thiruvarulTemplate,payanamTemplate].map(t=>t.id);
const videoIds=['temple-v1',...VIDEO_CATALOG.map(t=>t.id)];
for(const [media,ids] of [[websites,websiteIds],[videos,videoIds]]){
 assert.deepEqual(Object.keys(media).sort(),[...ids].sort(),'Every catalog design must have generated media');
 for(const [id,item] of Object.entries(media)){
  if(media===websites)assert.ok(item.namesPresent,id+' must show both names');
  for(const path of [item.poster,...Object.values(item.posters),...(item.preview?[item.preview]:[])]){
   assert.match(path,/^\/assets\/catalog-previews\/names-v1\/[\w/-]+\.(webp|mp4)$/);
   assert.ok((await fs.stat('public'+path)).size>0,id+' has an empty asset');
  }
 }
}
const manifest={websites:Object.fromEntries(Object.entries(websites).map(([id,{poster,posters,version}])=>[id,{poster,posters,version}])),videos:Object.fromEntries(videoIds.map(id=>[id,videos[id]]))};
await fs.writeFile('shared/catalog-preview-media.mjs','// Generated by scripts/assemble-named-preview-media.mjs. Catalog demos only.\nexport default '+JSON.stringify(manifest,null,2)+';\n');
const responsive=await read('src/catalog-posters.json');
for(const {poster,posters} of Object.values(websites))responsive[poster]=posters;
await fs.writeFile('src/catalog-posters.json',JSON.stringify(responsive,null,2)+'\n');
console.log(JSON.stringify({websites:websiteIds.length,videos:videoIds.length,allAssetsPresent:true}));
