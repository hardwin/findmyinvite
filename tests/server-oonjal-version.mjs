import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {loadVideoMaster,videoConfig,requireVideoRelease} from '../server/video-personalise.mjs';
import {pinVideoMasterVersion,videoNewOrSavedVersion} from '../shared/video-master-version.mjs';
import {oonjalRecordingId,usesOriginalOonjalAudio} from '../shared/music-selection.mjs';
import {normalizeVideoContent,videoDefinition} from '../shared/video-personalization.mjs';
import {prepareSceneMaster} from '../server/video-scene-details.mjs';
const id='film-oonjal-v1';
const publicFile=path=>readFile(new URL('../public'+path,import.meta.url));
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');

test('the released designer film only personalises the two names and wedding date',async()=>{
 const master=await loadVideoMaster(id,3);
 const config=await videoConfig({},id,{tracks:[],assignments:[]},3);
 const fields=config.form.steps.flatMap(step=>step.questions.map(q=>q.path));
 assert.deepEqual(fields,['brideEn','groomEn','weddingDate']);
 assert.deepEqual(config.photoSlots,[]);
 assert.equal(config.ready,false);
 assert.equal(config.defaults.music.id,oonjalRecordingId);
 assert.equal(videoNewOrSavedVersion(id,null),3);
 assert.equal(videoNewOrSavedVersion(id,{}),1);
 assert.deepEqual(await loadVideoMaster(id),master);
 assert.equal((await loadVideoMaster(id,1)).version,1);
 assert.equal(config.name,'Maapla Veetla Double okay :P');
 assert.equal((await videoConfig({VIDEO_PERSONALISE_ENABLED:'1'},id,{tracks:[],assignments:[]})).ready,true);
 const env={VERCEL:'1',VIDEO_PERSONALISE_ENABLED:'1',VIDEO_SCENE_SNAPSHOT_ID:'legacy-worker',BLOB_READ_WRITE_TOKEN:'fixture'};
 assert.throws(()=>requireVideoRelease(master,env),/not configured/);
 assert.doesNotThrow(()=>requireVideoRelease(master,{...env,VIDEO_OONJAL_SNAPSHOT_ID:'designer-worker'}));
 const legacy=await loadVideoMaster(id,1);
 assert.doesNotThrow(()=>requireVideoRelease(legacy,env));
 assert.throws(()=>pinVideoMasterVersion(id,{masterVersion:3},{payload:{}}),/different/);
 const example=videoDefinition(id,3).example,options={templateId:id,masterVersion:3,complete:true};
 const clean=normalizeVideoContent({...example,intro2:'OLD MONTH',music:{mode:'none'},photos:{bride:{}}},options);
 assert.deepEqual(clean,example);
 assert.throws(()=>normalizeVideoContent({...example,brideEn:''},options));
 assert.throws(()=>normalizeVideoContent({...example,weddingDate:'2027-02-30'},options));
 assert.equal(usesOriginalOonjalAudio(master,clean.music),true);
 assert.deepEqual((await prepareSceneMaster(master,clean)).output,{width:720,height:1280,fps:24,frames:828,duration:34.5});
 const lock=master.assets.sceneBundle,index=await publicFile(lock.path);
 assert.equal(sha(index),lock.sha256);
 for(const [path,hash] of Object.entries(JSON.parse(index).files))assert.equal(sha(await publicFile(path)),hash,path);
});
