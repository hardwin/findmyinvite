import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import handler from '../api/blog-page.mjs';
import content from '../api/content.mjs';
import {CANONICAL_ORIGIN,INDEX_H1,INDEX_TITLE,NOT_FOUND_HTML,PAGE_HEADER,blogIndexHtml,blogPostHtml,blogSlugFromRequest} from '../server/blog-page.mjs';
import {loadFilePosts,parseMarkdownPost,publishedPost,publishedPosts} from '../server/blog-posts.mjs';
const HOME='Create Invitation Webpage Online for All Events';
const SEED='halloween-invitation-webpage';
async function api(url,method='GET'){
 const res={headers:{},body:'',code:0,setHeader(k,v){this.headers[k]=v;},status(n){this.code=n;return this;},end(b){this.body=b||'';if(!this.code)this.code=this.statusCode||200;}};
 await handler({url,method,headers:{host:'findmyinvite.com','x-forwarded-proto':'https'}},res);
 return res;
}
async function contentApi(url){
 const res={headers:{},body:null,code:0,setHeader(k,v){this.headers[k]=v;},status(n){this.code=n;return this;},json(v){this.body=v;}};
 await content({url,method:'GET',headers:{host:'findmyinvite.com'}},res);
 return res;
}
test('blog index and seed post return unique 200 HTML, unknown slugs 404',async()=>{
 const files=await loadFilePosts();
 const seed=files.find(post=>post.slug===SEED);
 assert.equal(Boolean(seed),true);
 assert.equal(seed.published,true);
 const posts=await publishedPosts();
 assert.equal(posts.some(post=>post.slug===SEED),true);
 const index=await api('/blog');
 assert.equal(index.code,200);
 assert.equal(index.headers[PAGE_HEADER],'hit');
 assert.equal(index.headers['Content-Type'],'text/html; charset=utf-8');
 assert.equal(index.headers['X-Robots-Tag'],undefined);
 assert.match(String(index.body),new RegExp('<title>'+INDEX_TITLE.replace(/[|]/g,'\\|')+'</title>'));
 assert.match(String(index.body),new RegExp('<h1>'+INDEX_H1+'</h1>'));
 assert.match(String(index.body),new RegExp('<link rel="canonical" href="'+CANONICAL_ORIGIN+'/blog"'));
 assert.match(String(index.body),new RegExp(SEED));
 assert.equal(String(index.body).includes(HOME),false);
 assert.equal(String(index.body).includes('vercel.app'),false);
 const post=await api('/blog/'+SEED);
 assert.equal(post.code,200);
 assert.equal(post.headers[PAGE_HEADER],'hit');
 assert.equal(post.headers['Content-Type'],'text/html; charset=utf-8');
 assert.equal(String(post.body).includes('<title>'+seed.title+'</title>'),true);
 assert.equal(String(post.body).includes('<h1>'+seed.h1+'</h1>'),true);
 assert.equal(String(post.body).includes('<link rel="canonical" href="'+CANONICAL_ORIGIN+'/blog/'+SEED+'"'),true);
 assert.equal(String(post.body).includes(seed.description),true);
 assert.equal(String(post.body).includes('costume theme'),true);
 assert.equal(String(post.body).includes(HOME),false);
 assert.equal(String(post.body).includes('vercel.app'),false);
 assert.notEqual(String(index.body),String(post.body));
 const byQuery=await api('/api/blog-page?slug='+SEED);
 assert.equal(byQuery.code,200);
 assert.equal(String(byQuery.body).includes('<h1>'+seed.h1+'</h1>'),true);
 const missing=await api('/blog/this-should-404');
 assert.equal(missing.code,404);
 assert.equal(missing.headers[PAGE_HEADER],'404');
 assert.equal(missing.headers['X-Robots-Tag'],'noindex, nofollow');
 assert.equal(missing.body,NOT_FOUND_HTML);
 assert.equal(missing.headers['Content-Type'],'text/html; charset=utf-8');
 const invalid=await api('/blog/Not_A_Slug');
 assert.equal(invalid.code,404);
 const head=await api('/blog/this-should-404','HEAD');
 assert.equal(head.code,404);
 assert.equal(head.body,'');
 assert.equal(blogSlugFromRequest({url:'/api/blog-page?slug='+SEED}),SEED);
 assert.equal(blogSlugFromRequest({url:'/blog/'+SEED}),SEED);
 assert.equal(blogSlugFromRequest({url:'/blog'}), '');
 assert.equal(await publishedPost('this-should-404'),null);
 const html=blogPostHtml(seed);
 assert.match(html,/<h1>Halloween Invitation Webpage for Parties and Events<\/h1>/);
 assert.equal(html.includes(HOME),false);
 assert.match(blogIndexHtml([]),/No articles have been published yet/);
});
test('content API and sitemap list the file seed; Vercel blog rewrites beat guest-page and SPA',async()=>{
 const list=await contentApi('/api/content?kind=blog');
 assert.equal(list.code,200);
 assert.equal(Array.isArray(list.body.posts),true);
 assert.equal(list.body.posts.some(post=>post.slug===SEED),true);
 const one=await contentApi('/api/content?kind=blog&slug='+SEED);
 assert.equal(one.body.post.slug,SEED);
 assert.match(one.body.post.body,/WhatsApp/);
 const missing=await contentApi('/api/content?kind=blog&slug=this-should-404');
 assert.equal(missing.body.post,null);
 const bad=await contentApi('/api/content?kind=blog&slug=Not_A_Slug');
 assert.equal(bad.code,400);
 const sitemap=await readFile(new URL('../public/sitemap.xml',import.meta.url),'utf8');
 assert.match(sitemap,/https:\/\/findmyinvite.com\/blog</);
 for(const post of await loadFilePosts()){
  if(!post.published)continue;
  assert.match(sitemap,new RegExp('https://findmyinvite.com/blog/'+post.slug));
 }
 assert.equal(sitemap.includes('vercel.app'),false);
 const raw=await readFile(new URL('../content/blog/halloween-invitation-webpage.md',import.meta.url),'utf8');
 assert.equal(parseMarkdownPost(raw).slug,SEED);
 const vercel=JSON.parse(await readFile(new URL('../vercel.json',import.meta.url),'utf8'));
 const blogIndex=vercel.rewrites.findIndex(rule=>rule.source==='/blog');
 const blogPost=vercel.rewrites.findIndex(rule=>rule.source==='/blog/:slug');
 const guest=vercel.rewrites.findIndex(rule=>rule.destination==='/api/guest-page?slug=:slug');
 const spa=vercel.rewrites.find(rule=>rule.destination==='/index.html');
 assert.equal(vercel.rewrites[blogIndex].destination,'/api/blog-page');
 assert.equal(vercel.rewrites[blogPost].destination,'/api/blog-page?slug=:slug');
 assert.ok(blogIndex>0&&blogIndex<guest);
 assert.ok(blogPost>blogIndex&&blogPost<guest);
 const spaPattern=new RegExp(`^${spa.source}$`);
 assert.equal(spaPattern.test('/blog'),false);
 assert.equal(spaPattern.test('/blog/'+SEED),false);
 assert.equal(spaPattern.test('/blog/this-should-404'),false);
 assert.equal(spaPattern.test('/templates'),true);
 assert.equal(spaPattern.test('/invitations/haldi'),false);
 assert.equal(vercel.functions['api/blog-page.mjs'].includeFiles,'content/blog/**');
 assert.equal(vercel.functions['api/content.mjs'].includeFiles,'content/blog/**');
});
